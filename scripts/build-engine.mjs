#!/usr/bin/env node
/**
 * Bundles the simulation engine (src/lib/engine/run.ts and what it imports)
 * into one ES module that Claude Code downloads and runs on its own machine,
 * so its simulations cost the server nothing.
 *
 *   engine-dist/hydrodesk-engine.mjs  the bundle, served to signed-in clients by /api/engine
 *   public/engine-version.json     { version }, a static file the CLI checks cheaply
 *
 * The version is a hash of the bundle: any change to the engine gives a new
 * one, and the CLI fetches the new bundle before it simulates or saves again.
 * Runs before `next build` and `next dev` (package.json pre-scripts). Both
 * outputs are generated, so they are not committed.
 */
import { createHash } from "node:crypto";
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const out = await build({
  entryPoints: [join(root, "src/lib/engine/run.ts")],
  bundle: true,
  format: "esm",
  platform: "neutral",
  target: "node18",
  write: false,
  legalComments: "none",
  logLevel: "warning",
});
const code = out.outputFiles[0].text;
const version = createHash("sha256").update(code).digest("hex").slice(0, 12);
const bundle = `// HydroDesk simulation engine ${version}. Generated by scripts/build-engine.mjs; do not edit.\n`
  + `export const ENGINE_VERSION = ${JSON.stringify(version)};\n${code}`;

mkdirSync(join(root, "engine-dist"), { recursive: true });
writeFileSync(join(root, "engine-dist", "hydrodesk-engine.mjs"), bundle);
writeFileSync(join(root, "public", "engine-version.json"), JSON.stringify({ version }) + "\n");
console.log(`engine ${version}: ${Math.round(bundle.length / 1024)} kB`);
