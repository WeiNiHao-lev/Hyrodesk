const SIDE = new Set(["sludge", "backwash", "flush", "concentrate", "reject", "float", "cake", "filtrate", "supernatant", "solids", "brine", "pellets"]);

function diagram(fs: Flowsheet, result: SimulationResult): string {
  const W = 176, H = 58;
  if (fs.nodes.length === 0) return "";
  const xs = fs.nodes.map((n) => n.position.x), ys = fs.nodes.map((n) => n.position.y);
  const minX = Math.min(...xs) - 30, minY = Math.min(...ys) - 40;
  const maxX = Math.max(...xs) + W + 30, maxY = Math.max(...ys) + H + 50;
  const at = new Map(fs.nodes.map((n) => [n.id, n]));
  const flowOf = new Map(result.streams.concat(result.productStreams, result.wasteStreams, result.feedStreams).map((s) => [s.id, s.stream.flow]));
  const sinkTypes = new Set(["waste"]);

  const edges = fs.edges.map((e) => {
    const a = at.get(e.source), b = at.get(e.target);
    if (!a || !b) return "";
    const side = SIDE.has(String(e.sourceHandle)) || sinkTypes.has(b.type);
    // Side streams (backwash, concentrate, sludge) leave from the lower edge of
    // the block, so they do not draw over the main line.
    const sx = a.position.x + W, sy = a.position.y + (side && e.sourceHandle !== "out" ? H - 10 : H / 2);
    const tx = b.position.x, ty = b.position.y + H / 2;
    const color = side ? "#a0704a" : "#1d6fa5";
    let d: string;
    if (tx >= sx + 10 && side) {
      // Straight down to the row of its target, then along that row.
      d = `M${sx},${sy} H${sx + 14} V${ty} H${tx - 6}`;
    } else if (tx >= sx + 10) {
      const mx = sx + Math.max(14, (tx - sx) / 2);
      d = `M${sx},${sy} H${mx} V${ty} H${tx - 6}`;
    } else {
      // A recycle: down below both blocks and back.
      const low = Math.max(a.position.y, b.position.y) + H + 24;
      d = `M${sx},${sy} H${sx + 14} V${low} H${tx - 18} V${ty} H${tx - 6}`;
    }
    const f = flowOf.get(e.id);
    const lx = tx >= sx + 10 && !side ? sx + Math.max(14, (tx - sx) / 2) : sx + 14;
    const ly = tx >= sx + 10 ? (sy + ty) / 2 : Math.max(a.position.y, b.position.y) + H + 24;
    const label = f != null && f > 0
      ? `<text x="${lx + 4}" y="${ly - 4}" class="fl">${num(f, f < 10 ? 2 : 1)}</text>`
      : "";
    return `<path d="${d}" fill="none" stroke="${color}" stroke-width="1.6" ${side ? 'stroke-dasharray="5 3"' : ""} marker-end="url(#ah${side ? "s" : "m"})"/>${label}`;
  }).join("");

  const nodes = fs.nodes.map((n) => {
    const m = UNIT_BY_TYPE[n.type];
    const cat = m?.category ?? "network";
    const fill = cat === "membrane" ? "#fff6e6" : cat === "network" ? "#fdeef0" : cat === "storage" ? "#e8f6f3" : cat === "sludge" ? "#f3efe9" : cat === "biological" ? "#eaf7ef" : cat === "intake" ? "#e9f4fb" : "#eef7fa";
    const stroke = cat === "membrane" ? "#d9a441" : cat === "network" ? "#d58a97" : cat === "sludge" ? "#a0704a" : "#4c9bc4";
    const label = n.label.length > 24 ? `${n.label.slice(0, 23)}…` : n.label;
    return `<g><rect x="${n.position.x}" y="${n.position.y}" width="${W}" height="${H}" rx="9" fill="${fill}" stroke="${stroke}" stroke-width="1.3"/>`
      + `<text x="${n.position.x + 10}" y="${n.position.y + 20}" class="ty">${esc(m?.short ?? n.type.toUpperCase())}</text>`
      + `<text x="${n.position.x + 10}" y="${n.position.y + 40}" class="nm">${esc(label)}</text></g>`;
  }).join("");

  // Drawn at about the canvas scale, so block names stay readable; a long train
  // scrolls sideways inside its card instead of shrinking to fit.
  const w = maxX - minX, h = maxY - minY;
  return `<div class="dg"><svg viewBox="${minX} ${minY} ${w} ${h}" style="width:${Math.round(w * 0.72)}px" role="img" aria-label="process flow">
<defs>
<marker id="ahm" viewBox="0 0 10 10" refX="9" refY="5" markerWidth="7" markerHeight="7" orient="auto"><path d="M0,0 L10,5 L0,10 z" fill="#1d6fa5"/></marker>
<marker id="ahs" viewBox="0 0 10 10" refX="9" refY="5" markerWidth="7" markerHeight="7" orient="auto"><path d="M0,0 L10,5 L0,10 z" fill="#a0704a"/></marker>
</defs>${edges}${nodes}</svg></div>`;
}

