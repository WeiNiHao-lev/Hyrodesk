/** A text the engineer wrote: each language shows its own version, or the original, marked as such. */
function multiText(m: Multi | undefined, source: WbLang, list: boolean): string {
  return LANGS.map((l) => {
    const own = m?.[l]?.trim();
    const text = own || m?.[source]?.trim() || "";
    if (!text) return "";
    const tag = !own && l !== source ? `<span class="orig">${ORIGINAL[l]} · ${LANG_NAME[source][l]}</span>` : "";
    const body = list
      ? `<ul>${text.split(/\n+/).map((x) => x.replace(/^[-•*]\s*/, "").trim()).filter(Boolean).map((x) => `<li>${esc(x)}</li>`).join("")}</ul>`
      : `<p class="note">${esc(text)}</p>`;
    return `<div data-l="${l}">${tag}${body}</div>`;
  }).join("");
}

