/* ------------------------------------------------------------- the diagram
 * Drawn from the canvas layout, in the canvas's own units (one unit = one
 * pixel), so names and numbers read at a comfortable size; a long train
 * scrolls sideways. Lines are routed around the blocks: each connection tries
 * a few orthogonal shapes and keeps the first that crosses no other block, so
 * a backwash or sludge line never runs along or through a block it does not
 * belong to. Flow numbers sit at the middle of the longest straight piece of
 * their line, never at the arrow.
 */

const SIDE = new Set(["sludge", "backwash", "flush", "concentrate", "reject", "float", "cake", "filtrate", "supernatant", "solids", "brine", "pellets"]);
const BW = 176, BH = 58, PAD = 8;

type Pt = [number, number];
interface Box { id: string; x1: number; y1: number; x2: number; y2: number }

/** Does an axis-aligned segment pass through the inside of a box? */
function crosses(a: Pt, b: Pt, r: Box): boolean {
  if (a[1] === b[1]) {
    const lo = Math.min(a[0], b[0]), hi = Math.max(a[0], b[0]);
    return a[1] > r.y1 && a[1] < r.y2 && hi > r.x1 && lo < r.x2;
  }
  const lo = Math.min(a[1], b[1]), hi = Math.max(a[1], b[1]);
  return a[0] > r.x1 && a[0] < r.x2 && hi > r.y1 && lo < r.y2;
}

function hits(pts: Pt[], boxes: Box[], from: string, to: string): number {
  let n = 0;
  for (let i = 0; i < pts.length - 1; i++) {
    for (const r of boxes) {
      if (i === 0 && r.id === from) continue;
      if (i === pts.length - 2 && r.id === to) continue;
      if (crosses(pts[i], pts[i + 1], r)) n++;
    }
  }
  return n;
}

/** Drops repeated points and merges straight runs. */
function tidy(pts: Pt[]): Pt[] {
  const out: Pt[] = [];
  for (const p of pts) {
    const q = out[out.length - 1];
    if (q && q[0] === p[0] && q[1] === p[1]) continue;
    const o = out[out.length - 2];
    if (o && q && ((o[0] === q[0] && q[0] === p[0]) || (o[1] === q[1] && q[1] === p[1]))) out[out.length - 1] = p;
    else out.push(p);
  }
  return out;
}

/** Splits a block name over at most two lines of about `max` characters. */
function wrap(s: string, max = 20): string[] {
  const words = s.split(/\s+/);
  const lines: string[] = [];
  let cur = "";
  for (const w of words) {
    if (!cur) cur = w;
    else if ((cur + " " + w).length <= max) cur += " " + w;
    else { lines.push(cur); cur = w; }
  }
  if (cur) lines.push(cur);
  if (lines.length > 2) lines.splice(1, lines.length - 1, `${lines.slice(1).join(" ").slice(0, max - 1)}…`);
  return lines.map((l) => (l.length > max + 2 ? `${l.slice(0, max)}…` : l));
}

/**
 * Block positions for the drawing. The canvas lets blocks sit closer than
 * a drawn block is wide; such a layout is spread out evenly (never squeezed)
 * until every block has room around it for lines to pass.
 */
function layout(fs: Flowsheet): Map<string, { x: number; y: number }> {
  const ps = fs.nodes.map((n) => ({ id: n.id, x: n.position.x, y: n.position.y }));
  let minDx = Infinity;
  for (const p of ps) for (const q of ps) {
    const dx = Math.abs(p.x - q.x);
    if (p !== q && dx > 1 && Math.abs(p.y - q.y) < BH + 10) minDx = Math.min(minDx, dx);
  }
  const kx = Number.isFinite(minDx) && minDx < BW + 56 ? (BW + 56) / minDx : 1;
  let minDy = Infinity;
  for (const p of ps) for (const q of ps) {
    const dy = Math.abs(p.y - q.y);
    if (p !== q && dy > 1 && Math.abs(p.x - q.x) * kx < BW + 10) minDy = Math.min(minDy, dy);
  }
  const ky = Number.isFinite(minDy) && minDy < BH + 48 ? (BH + 48) / minDy : 1;
  return new Map(ps.map((p) => [p.id, { x: Math.round(p.x * kx), y: Math.round(p.y * ky) }]));
}

/**
 * The routed connections, with how many blocks each still crosses (0 when a
 * clear route was found). Exported for the self-test.
 */
export function routeEdges(fs: Flowsheet, result: SimulationResult) {
  const at = new Map(fs.nodes.map((n) => [n.id, n]));
  const pos = layout(fs);
  const boxes: Box[] = fs.nodes.map((n) => {
    const p = pos.get(n.id)!;
    return { id: n.id, x1: p.x - PAD, y1: p.y - PAD, x2: p.x + BW + PAD, y2: p.y + BH + PAD };
  });
  const flowOf = new Map(result.streams.concat(result.productStreams, result.wasteStreams, result.feedStreams).map((s) => [s.id, s.stream.flow]));
  // Lines that share a lane above or below the blocks are spaced 12 apart.
  const lanes = new Map<string, number>();
  const laneKey = (base: number, dir: 1 | -1) => `${dir}:${Math.round(base / 10)}`;
  const laneY = (base: number, dir: 1 | -1) => base + dir * (lanes.get(laneKey(base, dir)) ?? 0) * 12;

  const drawn: { id: string; pts: Pt[]; side: boolean; flow?: number; crossings: number }[] = [];
  for (const e of fs.edges) {
    const a = at.get(e.source), b = at.get(e.target);
    if (!a || !b) continue;
    const pa = pos.get(a.id)!, pb = pos.get(b.id)!;
    const side = SIDE.has(String(e.sourceHandle)) || b.type === "waste";
    // Side streams leave from the lower part of the block, clear of the main line.
    const sx = pa.x + BW, sy = pa.y + (side && e.sourceHandle !== "out" ? BH - 12 : BH / 2);
    const tx = pb.x, ty = pb.y + BH / 2;
    const end: Pt = [tx - 2, ty];
    const cands: { pts: Pt[]; lane?: [number, 1 | -1] }[] = [];

    if (tx >= sx + 24) {
      if (Math.abs(sy - ty) < 0.5) cands.push({ pts: [[sx, sy], end] });
      // Vertical drops in the gaps between columns, nearest the source first
      // for side streams (they leave at once), the middle first for the main line.
      const cols = boxes
        .filter((r) => r.y2 > Math.min(sy, ty) && r.y1 < Math.max(sy, ty))
        .map((r) => [r.x1, r.x2] as const);
      const xs = new Set<number>([Math.round((sx + tx) / 2), sx + 16, tx - 18]);
      for (const [, x2] of cols) {
        const next = cols.filter(([x1]) => x1 > x2).map(([x1]) => x1);
        if (next.length) xs.add(Math.round((x2 + Math.min(...next)) / 2));
      }
      const order = [...xs].filter((x) => x > sx + 10 && x < tx - 10)
        .sort((p, q) => side ? p - q : Math.abs(p - (sx + tx) / 2) - Math.abs(q - (sx + tx) / 2));
      for (const x of order) cands.push({ pts: [[sx, sy], [x, sy], [x, ty], end] });
    }

    // Out to the right, along a horizontal corridor, and in from the left: the
    // corridor is a gap between rows of blocks, or a lane below or above them all.
    const x1s = [sx + 16, sx + 12];
    const x2s = [tx - 20, tx - 12];
    const spanLo = Math.min(sx, tx) - 24, spanHi = Math.max(sx, tx) + 24;
    const under = boxes.filter((r) => r.x2 > spanLo && r.x1 < spanHi);
    const edgesY = under.flatMap((r) => [r.y1, r.y2]).sort((p, q) => p - q);
    const gaps: number[] = [];
    for (const r of under) {
      const nextTop = under.filter((o) => o.y1 >= r.y2).map((o) => o.y1);
      if (nextTop.length) {
        const top = Math.min(...nextTop);
        if (top - r.y2 >= 10) gaps.push(Math.round((r.y2 + top) / 2));
      }
    }
    gaps.sort((p, q) => Math.abs(p - (sy + ty) / 2) - Math.abs(q - (sy + ty) / 2));
    for (const y of [...new Set(gaps)]) for (const x1 of x1s) for (const x2 of x2s) {
      cands.push({ pts: [[sx, sy], [x1, sy], [x1, y], [x2, y], [x2, ty], end] });
    }
    const below = Math.max(edgesY[edgesY.length - 1] ?? 0, sy, ty) + 14;
    const above = Math.min(edgesY[0] ?? 0, sy, ty) - 14;
    for (const [base, dir] of [[below, 1], [above, -1]] as const) {
      const y = laneY(base, dir);
      for (const x1 of x1s) for (const x2 of x2s) {
        cands.push({ pts: [[sx, sy], [x1, sy], [x1, y], [x2, y], [x2, ty], end], lane: [base, dir] });
      }
    }

    let best = cands[0], bestHits = Infinity;
    for (const c of cands) {
      const h = hits(c.pts, boxes, a.id, b.id);
      if (h < bestHits) { best = c; bestHits = h; }
      if (h === 0) break;
    }
    if (best.lane) {
      const k = laneKey(...best.lane);
      lanes.set(k, (lanes.get(k) ?? 0) + 1);
    }
    drawn.push({ id: e.id, pts: tidy(best.pts), side, flow: flowOf.get(e.id), crossings: bestHits });
  }
  return { drawn, boxes, pos };
}

function diagram(fs: Flowsheet, result: SimulationResult): string {
  if (fs.nodes.length === 0) return "";
  const { drawn, boxes, pos } = routeEdges(fs, result);

  const lines = drawn.map(({ pts, side }) => {
    const d = pts.map((p, i) => `${i ? "L" : "M"}${p[0]},${p[1]}`).join(" ");
    return `<path d="${d}" fill="none" stroke="${side ? "#a0704a" : "#1d6fa5"}" stroke-width="${side ? 1.6 : 2}"${side ? ' stroke-dasharray="6 4"' : ""} marker-end="url(#ah${side ? "s" : "m"})"/>`;
  }).join("");

  // Numbers after all lines, so no line covers a number. Each number goes to
  // the middle of a straight piece of its own line where it overlaps no block,
  // no other line and no other number; horizontal pieces first, as they read
  // better, and the longest first.
  type Rect = [number, number, number, number];
  const overlap = (r: Rect, o: Rect) => r[0] < o[2] && r[2] > o[0] && r[1] < o[3] && r[3] > o[1];
  const segRect = (p: Pt, q: Pt): Rect => [Math.min(p[0], q[0]) - 1, Math.min(p[1], q[1]) - 1, Math.max(p[0], q[0]) + 1, Math.max(p[1], q[1]) + 1];
  const blockRects: Rect[] = boxes.map((r) => [r.x1 + PAD, r.y1 + PAD, r.x2 - PAD, r.y2 - PAD]);
  const placed: Rect[] = [];
  const labels = drawn.map(({ pts, flow }, di) => {
    if (flow == null || !(flow > 0)) return "";
    const txt = num(flow, flow < 10 ? 2 : 1);
    const w = txt.length * 8.4 + 4;
    const others: Rect[] = drawn.flatMap((d, k) => (k === di ? [] : d.pts.slice(1).map((q, m) => segRect(d.pts[m], q))));
    let best: { x: number; y: number; mid: boolean; r: Rect; score: number } | null = null;
    for (let i = 0; i < pts.length - 1; i++) {
      const [p, q] = [pts[i], pts[i + 1]];
      const horiz = p[1] === q[1];
      const len = Math.abs(q[0] - p[0]) + Math.abs(q[1] - p[1]);
      if (len < (horiz ? w + 10 : 30)) continue;
      for (const f of [0.5, 0.35, 0.65, 0.25, 0.75]) {
        const x = horiz ? p[0] + (q[0] - p[0]) * f : p[0] + 7;
        const y = horiz ? p[1] - 7 : p[1] + (q[1] - p[1]) * f + 5;
        const r: Rect = horiz ? [x - w / 2, y - 13, x + w / 2, y + 3] : [x - 2, y - 13, x + w, y + 3];
        const clash = blockRects.some((o) => overlap(r, o)) || others.some((o) => overlap(r, o)) || placed.some((o) => overlap(r, o));
        const score = (clash ? -1e6 : 0) + (horiz ? len * 1.4 : len) - Math.abs(f - 0.5) * 60;
        if (!best || score > best.score) best = { x, y, mid: horiz, r, score };
      }
    }
    if (!best) {
      // A line too short for its number: put it beside the first piece.
      const [p] = pts;
      best = { x: p[0] + 4, y: p[1] - 7, mid: false, r: [p[0] + 2, p[1] - 20, p[0] + 4 + w, p[1] - 4], score: 0 };
    }
    placed.push(best.r);
    return `<text x="${best.x.toFixed(1)}" y="${best.y.toFixed(1)}"${best.mid ? ' text-anchor="middle"' : ""} class="fl">${txt}</text>`;
  }).join("");

  const nodes = fs.nodes.map((n) => {
    const m = UNIT_BY_TYPE[n.type];
    const { x, y } = pos.get(n.id)!;
    const ln = wrap(n.label);
    const name = ln.length === 1
      ? `<text x="${x + 12}" y="${y + 42}" class="nm">${esc(ln[0])}</text>`
      : `<text x="${x + 12}" y="${y + 35}" class="nm">${esc(ln[0])}</text><text x="${x + 12}" y="${y + 51}" class="nm">${esc(ln[1])}</text>`;
    return `<g><rect x="${x}" y="${y}" width="${BW}" height="${BH}" rx="8" fill="#ffffff" stroke="#93a8b8" stroke-width="1.3"/>`
      + `<text x="${x + 12}" y="${y + 17}" class="ty">${esc(m?.short ?? n.type.toUpperCase())}</text>${name}</g>`;
  }).join("");

  const allY = drawn.flatMap((d) => d.pts.map((p) => p[1]));
  const allX = drawn.flatMap((d) => d.pts.map((p) => p[0]));
  const minX = Math.min(...boxes.map((r) => r.x1), ...allX) - 24;
  const maxX = Math.max(...boxes.map((r) => r.x2), ...allX) + 24;
  const minY = Math.min(...boxes.map((r) => r.y1), ...allY) - 26;
  const maxY = Math.max(...boxes.map((r) => r.y2), ...allY) + 26;
  const w = maxX - minX, h = maxY - minY;
  return `<div class="dg"><svg viewBox="${minX} ${minY} ${w} ${h}" style="width:${Math.round(w)}px" role="img" aria-label="process flow">
<defs>
<marker id="ahm" viewBox="0 0 10 10" refX="9" refY="5" markerWidth="7" markerHeight="7" orient="auto"><path d="M0,0 L10,5 L0,10 z" fill="#1d6fa5"/></marker>
<marker id="ahs" viewBox="0 0 10 10" refX="9" refY="5" markerWidth="7" markerHeight="7" orient="auto"><path d="M0,0 L10,5 L0,10 z" fill="#a0704a"/></marker>
</defs>${lines}${nodes}${labels}</svg></div>`;
}

