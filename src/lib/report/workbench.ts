/** A phrase in all three languages; the page shows one at a time. */
function tr(t: Tr): string {
  return `<span data-l="zh">${esc(t.zh)}</span><span data-l="en">${esc(t.en)}</span><span data-l="id">${esc(t.id)}</span>`;
}
