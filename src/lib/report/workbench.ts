/**
 * What HydroDesk can tell is still missing before the simulation can be
 * relied on, in three languages: parameters the standard asks for that the
 * mass balance cannot prove, gaps in the raw-water analysis, and the state of
 * the site-visit checklist when there is one.
 */
export function suggestDataNeeded(
  fs: Flowsheet, result: SimulationResult,
  prepare?: { answered: number; total: number; criticalOpen: number } | null,
): Required<Multi>[] {
  const out: Required<Multi>[] = [];
  if (!fs.feed.name?.trim()) {
    out.push({
      zh: "原水来源及水质分析报告（取样地点、日期、化验单位）",
      en: "Raw-water source and analysis report (sampling point, date, laboratory)",
      id: "Sumber air baku dan laporan analisis (titik sampling, tanggal, laboratorium)",
    });
  }
  for (const f of validateFeed(fs.feed).filter((x) => x.severity === "fail" || x.severity === "warn").slice(0, 4)) {
    const t = FEED_FINDING[f.title];
    // The missing-parameter finding names what is missing; say which.
    const which = f.title === "Parameters missing from the analysis" ? ` (${f.detail.replace(/^Not provided:\s*/, "").replace(/\.$/, "")})` : "";
    out.push({
      zh: `原水水质：${t?.zh ?? f.title}${which}`,
      en: `Raw-water analysis: ${f.title}${which}`,
      id: `Analisis air baku: ${t?.id ?? f.title}${which}`,
    });
  }
  const product = result.productStreams[0]?.stream;
  if (product) {
    for (const r of checkCompliance(product, fs.basis.standard).filter((x) => x.notModelled)) {
      const p = PARAM[r.label];
      out.push({
        zh: `${p?.zh ?? r.label}：物料平衡无法证明，需由设计和取样验证`,
        en: `${r.label}: not carried by the mass balance; prove by design and sampling`,
        id: `${p?.id ?? r.label}: tidak dihitung neraca massa; buktikan lewat desain dan sampling`,
      });
    }
  }
  if (prepare) {
    if (prepare.answered === 0) {
      out.push({ zh: "现场踏勘清单尚未开始", en: "Site-visit checklist not started", id: "Checklist kunjungan lapangan belum dimulai" });
    } else if (prepare.answered < prepare.total) {
      out.push({
        zh: `现场踏勘清单：已回答 ${prepare.answered}/${prepare.total} 项，${prepare.criticalOpen} 项关键问题待落实`,
        en: `Site-visit checklist: ${prepare.answered} of ${prepare.total} answered, ${prepare.criticalOpen} critical questions open`,
        id: `Checklist kunjungan lapangan: ${prepare.answered} dari ${prepare.total} terjawab, ${prepare.criticalOpen} pertanyaan kritis belum terjawab`,
      });
    }
  }
  return out;
}

